"""Build the application interface contract from design_system/.

Run with --check in validation; generated CSS must never be edited directly.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design_system"
TARGET = ROOT / "static/controls.css"


def build():
    manifest = json.loads((SOURCE / "tokens.json").read_text())

    def rule(selector, tokens):
        declarations = []
        for name, value in tokens.items():
            if not re.fullmatch(r"[a-z][a-z0-9-]*", name):
                raise ValueError(f"Invalid interface token: {name}")
            if not isinstance(value, str) or any(c in value for c in "{};<>\n"):
                raise ValueError(f"Invalid interface value: {name}")
            declarations.append(f"--{name}:{value}")
        return selector + "{" + ";".join(declarations) + "}\n"

    css = "/* GENERATED by tools/build_interface_system.py. Edit design_system/ instead. */\n"
    css += rule(":root", manifest["tokens"])
    for mode in manifest["modes"]:
        block = rule(mode["query"], mode["tokens"])
        css += f"@media{mode['media']}{{{block}}}\n" if "media" in mode else block
    components = (SOURCE / "components.css").read_text()
    for name, query in manifest["breakpoints"].items():
        components = components.replace(f"@media (--{name})", f"@media{query}")
    if re.search(r"@media\s*\(--", components):
        raise ValueError("Unknown interface breakpoint")
    css += components
    defined = set(re.findall(r"--([\w-]+)\s*:", css))
    references = set(re.findall(r"var\(--([\w-]+)", css))
    palette = {"ink", "white", "bg", "green", "line", "muted", "red", "dk-accent", "brand-teal-soft", "surface-subtle", "shadow"}
    if missing := references - defined - palette:
        raise ValueError(f"Undefined interface tokens: {sorted(missing)}")
    return css


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = build()
    themes = SOURCE / "themes.css"
    theme_target = ROOT / "static/themes.css"
    calendar_source = SOURCE / "calendar.js"
    calendar_target = ROOT / "static/calendar.js"
    notice_source = SOURCE / "notice-cards.js"
    notice_target = ROOT / "static/service-status-feed.js"
    if args.check:
        if notice_target.read_text() != notice_source.read_text():
            parser.exit(1, "Shared notice cards are stale; rebuild interface system\n")
        if calendar_target.read_text() != calendar_source.read_text():
            parser.exit(1, "Shared calendar is stale; rebuild interface system\n")
        if theme_target.read_text() != themes.read_text():
            parser.exit(1, "Interface themes are stale; rebuild interface system\n")
        if not TARGET.exists() or TARGET.read_text() != expected:
            parser.exit(1, "Interface CSS is stale; run python tools/build_interface_system.py\n")
    else:
        TARGET.write_text(expected)
        theme_target.write_text(themes.read_text())
        calendar_target.write_text(calendar_source.read_text())
        notice_target.write_text(notice_source.read_text())


if __name__ == "__main__":
    main()
